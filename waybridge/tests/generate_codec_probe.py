#!/usr/bin/env python3
"""Regenerate tiny 256x256 green capability samples through the actual NVENC adapter."""
from pathlib import Path
import subprocess
import shutil

ROOT = Path(__file__).resolve().parents[1]
(ROOT / "build/tests").mkdir(parents=True, exist_ok=True)
subprocess.run(["cc", "-std=c11", "-Wall", "-Wextra", "-Werror", "tests/generate_codec_stream.c", "native/nvenc.c", "-o", "build/tests/generate-codec-stream", *subprocess.check_output(["pkg-config", "--cflags", "--libs", "libavcodec", "libavutil"], text=True).split()], cwd=ROOT, check=True)
header = "// Generated by tests/generate_codec_probe.py from our own solid-green NVENC fixture.\n#pragma once\n#include <cstdint>\n"
for kind, name, extension in ((4, "Hevc", "hevc"), (5, "Av1", "obu")):
    path = ROOT / f"build/tests/probe.{extension}"
    output = subprocess.check_output([str(ROOT / "build/tests/generate-codec-stream"), str(kind), "256", "256", str(path)], text=True)
    length = int(output.splitlines()[0].split()[1])
    data = path.read_bytes()[:length]
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-f", extension, "-i", "pipe:0", "-f", "null", "-"], input=data, check=True)
    header += f"inline constexpr uint8_t {name}CapabilitySample[] = {{\n"
    for start in range(0, len(data), 16):
        header += "  " + ", ".join(f"0x{byte:02x}" for byte in data[start:start+16]) + ",\n"
    header += "};\n"
(ROOT / "client/video_capability_samples.h").write_text(header)

if shutil.which("clang-format"):
    subprocess.run(["clang-format", "-i", str(ROOT / "client/video_capability_samples.h")], check=True)
