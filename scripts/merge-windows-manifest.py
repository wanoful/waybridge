#!/usr/bin/env python3
"""Cross-host equivalent of mt -manifest A B -out:C for SDK-generated manifests.

Input registrations are generated by the unmodified Microsoft Windows App SDK
targets. This only merges their XML with our application manifest; it does not
invent WinRT registrations or rewrite the NuGet cache.
"""
import copy
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ASM = "urn:schemas-microsoft-com:asm.v1"
ET.register_namespace("", ASM)
ET.register_namespace("asmv3", "urn:schemas-microsoft-com:asm.v3")
ET.register_namespace("winrtv1", "urn:schemas-microsoft-com:winrt.v1")


def main():
    args = sys.argv[1:]
    start = args.index("-manifest") + 1
    output_arg = next(a for a in args if a.startswith("-out:"))
    paths = args[start:args.index(output_arg)]
    output = output_arg[len("-out:"):]
    root = ET.Element("{" + ASM + "}assembly", {"manifestVersion": "1.0"})
    for value in paths:
        path = Path(value)
        if not path.exists():
            path = Path(value.replace("\\", "/"))
        document = ET.parse(path).getroot()
        for child in document:
            if child.tag.endswith("assemblyIdentity"):
                for existing in list(root):
                    if existing.tag.endswith("assemblyIdentity"):
                        root.remove(existing)
                root.insert(0, copy.deepcopy(child))
            else:
                root.append(copy.deepcopy(child))
    if not root.findall(".//{urn:schemas-microsoft-com:winrt.v1}activatableClass"):
        raise ValueError("Windows App SDK generated no WinRT class registrations")
    # .NET on Unix and MSBuild's file tasks normalize backslashes differently.
    for destination in {Path(output), Path(output.replace("\\", "/"))}:
        destination.parent.mkdir(parents=True, exist_ok=True)
        ET.ElementTree(root).write(destination, encoding="utf-8", xml_declaration=True)


if __name__ == "__main__":
    main()
