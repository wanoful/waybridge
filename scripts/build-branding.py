#!/usr/bin/env python3
"""Regenerate checked-in Windows branding from the repo's SVG sources.
Requires rsvg-convert and Pillow; regular builds use the committed outputs.
"""
from pathlib import Path
import io
import subprocess
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/branding'

def png(name, edge):
    return subprocess.check_output(['rsvg-convert', '-w', str(edge), '-h', str(edge), str(ASSETS / (name + '.svg'))])

brand = png('waybridge', 256)
(ASSETS / 'waybridge.png').write_bytes(brand)
Image.open(io.BytesIO(brand)).save(ASSETS / 'waybridge.ico', sizes=[(s, s) for s in [16, 20, 24, 32, 40, 48, 64, 128, 256]])
arrays = []
for name, edge, symbol in [('waybridge-badge', 64, 'badge'), ('waybridge-placeholder', 128, 'placeholder')]:
    data = png(name, edge)
    (ASSETS / (name + '.png')).write_bytes(data)
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i+16]) for i in range(0, len(data), 16)]
    arrays.append('inline constexpr unsigned char ' + symbol + '[] = {\n  ' + ',\n  '.join(rows) + '\n};')
(ROOT / 'client/branding_assets.h').write_text('// Generated by scripts/build-branding.py. Do not edit.\n#pragma once\nnamespace BrandingAssets {\n' + '\n'.join(arrays) + '\n}\n')
